function showRecipe(recipe) {
  //   var recipe = recipes[0];

  var lables = document.getElementById("labels");
  lables.innerHTML = `<div class="badge bg-success bg-opacity-25 text-success fw-medium">
     ${recipe.level}</div>
     <div class="badge bg-primary bg-opacity-25 text-primary fw-medium">
    ${recipe.category} </div>`;

  var reviews = document.getElementById("reviews");
  reviews.innerHTML = `<div class="badge rounded-pill bg-light text-dark p-3 d-flex gap-2 fs-6 align-items-center">
                                <i class="fa-solid fa-star text-warning "></i>
                                <p class=" m-0 ">${recipe.reviews.star}</p>
                                <p class=" m-0 text-secondary fw-normal ">${recipe.reviews.review}</p>
                            </div>`;

  var recipeName = document.getElementById("recipeName");
  recipeName.innerHTML = recipe.name;

  var imgRecipe = document.getElementById("imgRecipe");
  imgRecipe.src = recipe.image;

  var desRecipe = document.getElementById("recipeDescription");
  desRecipe.innerHTML = recipe.description;

  var prepTime = document.getElementById("prepTime");
  prepTime.innerHTML = recipe.prepTime;

  var cookTime = document.getElementById("cookTime");
  cookTime.innerHTML = recipe.cookTime;

  var servings = document.getElementById("servings");
  servings.innerHTML = recipe.servings;

  var ingredientsHTML = "";
  for (var i = 0; i < recipe.ingredients.length; i++) {
    ingredientsHTML += `<li class=" d-flex gap-2 p-2"> <span
       class="p-1 bg-orangr-g circle-10 rounded-circle d-flex align-items-center justify-content-center">
       <span class="text-light">${i + 1}</span>
       </span>${recipe.ingredients[i]} </li>`;
  }
  var listIngredients = document.getElementById("listIngredients");
  listIngredients.innerHTML = ingredientsHTML;

  var instructionsHTML = "";
  for (var i = 0; i < recipe.instructions.length; i++) {
    instructionsHTML += `<li class=" d-flex align-items-center gap-2 p-2"> <span
     class="p-1 bg-orangr-g circle-40 rounded-4 d-flex align-items-center justify-content-center">
    <span class="text-light fw-bold">${i + 1}</span>
    </span>${recipe.instructions[i]}
   </li>`;
  }
  var listInstructions = document.getElementById("listInstructions");
  listInstructions.innerHTML = instructionsHTML;

  var tipsHtml = "";
  for (var i = 0; i < recipe.tips.length; i++) {
    tipsHtml += `<div class="bg-warning bg-opacity-10 my-3 px-2 py-3 rounded-3 border-4 border-start border-warning d-flex gap-2 align-items-center">
     <div class="p-1 bg-orangr-g circle-10 rounded-circle d-flex align-items-center justify-content-center">
     <i class="fa-solid fa-check text-light fa-xs"></i>
     </div>
       <li>${recipe.tips[i]}</li>
      </div>`;
  }
  var tipsReipe = document.getElementById("tips");
  tipsReipe.innerHTML = tipsHtml;

  var calories = document.getElementById("calories");
  calories.innerHTML = ` <h3 class="fw-bold fs-5 m-0">${recipe.nutrition.calories}</h3>`;

  var protein = document.getElementById("protein");
  protein.innerHTML = ` <h3 class="fw-bold fs-5 m-0">${recipe.nutrition.protein}</h3>`;

  var carbohydrates = document.getElementById("carbohydrates");
  carbohydrates.innerHTML = ` <h3 class="fw-bold fs-5 m-0">${recipe.nutrition.carbohydrates}</h3>`;

  var fat = document.getElementById("fat");
  fat.innerHTML = ` <h3 class="fw-bold fs-5 m-0">${recipe.nutrition.fat}</h3>`;

  var fiber = document.getElementById("fiber");
  fiber.innerHTML = ` <h3 class="fw-bold fs-5 m-0">${recipe.nutrition.fiber}</h3>`;

  var sodium = document.getElementById("sodium");
  sodium.innerHTML = ` <h3 class="fw-bold fs-5 m-0">${recipe.nutrition.sodium}</h3>`;

  var cookTime = parseInt(recipe.cookTime);
  var showAlert = document.getElementById("showAlert");
  if (cookTime > 40) {
    showAlert.innerHTML = ` <div class=" border-bottom px-4 pb-3 ">
    <div class=" d-flex align-items-center gap-3 bg-opacity-10 border-start border-4 border-danger p-4 rounded-3">
    <span class=""><i
    class="fa-solid fa-triangle-exclamation fs-20 text-danger"></i></span>
    <div class="">
    <p class=" mb-1 fw-bold text-danger fs-13">Extended Preparation Time</p>
    <p class=" mb-1 text-danger fs-13">This recipe requires more than 45
    minutes to prepare.Plan accordingly!</p>
      </div>
     </div>
   </div>`;
  } else {
    showAlert.innerHTML = `<div class=" border-bottom p-4 d-none">
   <div class="alert alert-danger mb-0">
   Extended Preparation Time
   </div>
   </div>`;
  }
}
